"""Generate the code-derived sections of the AI knowledge pack.

The knowledge pack (schema + cookbook + portable guide) is what an external AI
reads to author and diagnose Ambience scenes. Its *curated* prose is hand-
written, but the exhaustive condition/action reference is derived from the
shipped code here so it can never go stale: a new condition or a changed
`services.yaml` regenerates the reference, and `make ai-docs-check` fails a push
(and a release) that forgot to commit the regenerated output.

Run:  make ai-docs        (regenerate)
      make ai-docs-check  (fail if the committed output is stale)
"""

from __future__ import annotations

import importlib
import inspect
import json
import pkgutil
from collections.abc import Callable
from pathlib import Path
from typing import Any

import yaml

import custom_components.ambience.conditions as conditions_pkg
from custom_components.ambience.const import AI_BUNDLE_VERSION

REPO_ROOT = Path(__file__).resolve().parent.parent
AI_DOCS_DIR = REPO_ROOT / "docs" / "developers" / "ai-authoring"
SKILL_REFS_DIR = REPO_ROOT / "ai" / "skill" / "ambience-author" / "reference"
SERVICES_YAML = REPO_ROOT / "custom_components" / "ambience" / "services.yaml"
MANIFEST = REPO_ROOT / "custom_components" / "ambience" / "manifest.json"


def ambience_minor() -> str:
    """The integration's MAJOR.MINOR from manifest.json — the Ambience version this
    pack is built for. The skill compares the bundle's `ambience_version` to it."""
    version = str(json.loads(MANIFEST.read_text(encoding="utf-8"))["version"])
    parts = version.split(".")
    major = parts[0] if parts else "0"
    minor = parts[1] if len(parts) > 1 else "0"
    return f"{major}.{minor}"


GENERATED_BANNER = (
    "<!-- AUTO-GENERATED by bin/gen_ai_docs.py — do not edit by hand. Run: make ai-docs -->"
)
GENERATED_END = "<!-- END GENERATED -->"

# A condition module exposes these as class attributes; a class missing any of
# them (a base/helper class) is not a shippable condition.
_REQUIRED_ATTRS = ("name", "description", "predicate_help", "input", "priority")

# The curated source files, in the order they appear in the portable guide.
# Missing files are skipped (so the generator runs before they're all authored).
_PORTABLE_PARTS = [
    ("Supported AI bundle format", "bundle-format.generated.md"),
    ("Config schema", "schema.md"),
    ("Import format", "import-format.md"),
    ("Condition reference", "condition-reference.generated.md"),
    ("Condition cookbook", "conditions-cookbook.md"),
    ("Actions", "actions.md"),
    ("Action reference", "action-reference.generated.md"),
    ("Reading a diagnostic bundle", "diagnostics-guide.md"),
]


def _collapse(text: str) -> str:
    """Flatten a multi-line help string to a single line for a markdown bullet."""
    return " ".join(text.split())


def discover_conditions() -> list[dict[str, Any]]:
    """Every shipped condition, discovered by scanning the conditions package, so
    adding a condition needs no edit here. Sorted by evaluation priority (desc)."""
    found: dict[str, dict[str, Any]] = {}
    for mod_info in pkgutil.iter_modules(conditions_pkg.__path__):
        if mod_info.name.startswith("_"):
            continue
        module = importlib.import_module(f"{conditions_pkg.__name__}.{mod_info.name}")
        for _, obj in inspect.getmembers(module, inspect.isclass):
            if obj.__module__ != module.__name__:
                continue
            if not all(getattr(obj, attr, None) is not None for attr in _REQUIRED_ATTRS):
                continue
            name = obj.name
            if not isinstance(name, str) or not name:
                continue
            found[name] = {
                "name": name,
                "description": obj.description,
                "predicate_help": obj.predicate_help,
                "input": obj.input,
                "priority": obj.priority,
            }
    return sorted(found.values(), key=lambda c: (-c["priority"], c["name"]))


def _render_reference(
    title: str,
    description: str,
    items: list[dict[str, Any]],
    formatter: Callable[[dict[str, Any]], list[str]],
) -> str:
    """A generated reference doc: the banner, a titled intro, one `formatter`-
    rendered block per item, and the end marker."""
    lines = [GENERATED_BANNER, "", f"# {title}", "", description, ""]
    for item in items:
        lines += formatter(item)
    lines += [GENERATED_END, ""]
    return "\n".join(lines)


def render_condition_reference(conditions: list[dict[str, Any]]) -> str:
    """The generated per-condition reference: `when` key, input widget, priority
    and purpose for every condition. The cookbook supplies the worked examples."""

    def fmt(c: dict[str, Any]) -> list[str]:
        return [
            f"## `{c['name']}`",
            "",
            f"- **Purpose:** {_collapse(c['description'])}",
            f"- **Input type:** `{c['input']}`",
            f"- **Priority:** {c['priority']} (higher conditions are evaluated first)",
            f"- **Help:** {_collapse(c['predicate_help'])}",
            "",
        ]

    return _render_reference(
        "Condition reference",
        "Every built-in condition usable under a scene's `when`. Each `when` key is one of "
        "these names; its value is that condition's predicate (or `null` to match anything). "
        "See `conditions-cookbook.md` for plain-English → predicate examples.",
        conditions,
        fmt,
    )


def discover_builtin_actions() -> list[dict[str, Any]]:
    """The Ambience built-in safe services from services.yaml (the always-available
    actions). Per-install exposed services vary and live in the AI bundle instead."""
    data = yaml.safe_load(SERVICES_YAML.read_text(encoding="utf-8")) or {}
    out: list[dict[str, Any]] = []
    for service, spec in data.items():
        spec = spec or {}
        out.append(
            {
                "service": f"ambience.{service}",
                "name": spec.get("name", service),
                "description": _collapse(str(spec.get("description", ""))),
                "fields": sorted((spec.get("fields") or {}).keys()),
            }
        )
    return sorted(out, key=lambda a: a["service"])


def render_action_reference(actions: list[dict[str, Any]]) -> str:
    """The generated reference for the built-in `ambience.*` safe services."""

    def fmt(a: dict[str, Any]) -> list[str]:
        fields = ", ".join(f"`{f}`" for f in a["fields"]) if a["fields"] else "_(none)_"
        return [
            f"## `{a['service']}`",
            "",
            f"- **Name:** {a['name']}",
            f"- **Description:** {a['description']}",
            f"- **Fields:** {fields}",
            "",
        ]

    return _render_reference(
        "Built-in action reference",
        "The always-available `ambience.*` safe services. The exposed services for a "
        "specific install (e.g. `light.turn_on`) and their field schemas live in that "
        "install's AI bundle under `actions`.",
        actions,
        fmt,
    )


def render_compatibility(bundle_format: int, version_minor: str) -> str:
    """The generated compatibility note: the Ambience version this pack was built
    for and the bundle format it understands, plus exactly how to update. Derived
    from manifest.json + the `AI_BUNDLE_VERSION` constant so it can't go stale."""
    lines = [
        GENERATED_BANNER,
        "",
        "# Pack compatibility",
        "",
        f"This pack was built for **Ambience {version_minor}.x** and understands "
        f"**AI bundle format {bundle_format}**.",
        "",
        "**Before authoring or diagnosing, check the bundle against this pack:**",
        "",
        f"1. **Version.** Take the bundle's `ambience_version` (e.g. `{version_minor}.2`), drop "
        f"the patch, and compare its major.minor to **{version_minor}** — compare each part as "
        "an **integer**, not as text (so e.g. `0.9` is *older* than `0.31`, since 9 < 31):",
        f"   - **newer than {version_minor}** → the user's Ambience is newer than this pack. "
        "**Stop. Do not author.** Update the plugin (below), then retry.",
        f"   - **older than {version_minor}** → the user's Ambience is older than this pack. "
        "Ask them to update Ambience (HACS) and re-download the bundle.",
        f"   - **same `{version_minor}`** → compatible, continue.",
        "2. **Format (structural backstop).** If the bundle's `ambience_ai_bundle` is greater "
        f"than **{bundle_format}**, also stop and update the plugin.",
        "",
        "## Updating the plugin",
        "",
        "On a version mismatch, give the user these exact steps (and, in Claude Code, offer to "
        "run the CLI form for them with `claude plugin ...`):",
        "",
        "```",
        "/plugin marketplace update ambience",
        "/plugin install ambience@ambience",
        "```",
        "",
        "If it doesn't take effect, a clean reinstall always works "
        "(`/plugin uninstall ambience@ambience` then `/plugin install ambience@ambience`). The "
        "updated skill loads on the **next session** — have them restart and re-run. To skip "
        "this every release, they can enable **auto-update** for the `ambience` marketplace "
        "(`/plugin` → Marketplaces → ambience → enable auto-update).",
        "",
        GENERATED_END,
        "",
    ]
    return "\n".join(lines)


def assemble_portable_doc(parts: list[tuple[str, str]]) -> str:
    """One self-contained markdown built from titled section bodies, suitable to
    paste/upload into any AI."""
    lines = [
        GENERATED_BANNER,
        "",
        "# Ambience — AI authoring & diagnosis guide",
        "",
        "This single document teaches an AI how to author and diagnose Home Assistant "
        "Ambience scene config. Paste it into your AI, then paste your downloaded "
        "**AI bundle** (Ambience panel → Download AI bundle) so the AI knows your real "
        "entities, areas and exposed actions.",
        "",
    ]
    for title, body in parts:
        lines += [f"# {title}", "", body.strip(), ""]
    return "\n".join(lines)


def _read_part(filename: str) -> str | None:
    path = AI_DOCS_DIR / filename
    return path.read_text(encoding="utf-8") if path.exists() else None


def main() -> None:
    AI_DOCS_DIR.mkdir(parents=True, exist_ok=True)

    condition_ref = render_condition_reference(discover_conditions())
    (AI_DOCS_DIR / "condition-reference.generated.md").write_text(condition_ref, encoding="utf-8")

    action_ref = render_action_reference(discover_builtin_actions())
    (AI_DOCS_DIR / "action-reference.generated.md").write_text(action_ref, encoding="utf-8")

    compatibility = render_compatibility(AI_BUNDLE_VERSION, ambience_minor())
    (AI_DOCS_DIR / "bundle-format.generated.md").write_text(compatibility, encoding="utf-8")

    # Assemble the portable guide from whatever curated + generated parts exist.
    parts: list[tuple[str, str]] = []
    for title, filename in _PORTABLE_PARTS:
        body = _read_part(filename)
        if body is not None:
            # Strip a generated child's banner/end markers so the guide carries
            # only the outer one.
            body = body.replace(GENERATED_BANNER, "").replace(GENERATED_END, "")
            parts.append((title, body))
    guide = assemble_portable_doc(parts)
    (AI_DOCS_DIR / "ambience-ai-guide.md").write_text(guide, encoding="utf-8")

    # Sync the full pack into the skill so the plugin ships a current, self-
    # contained copy (drift-gated together with the docs).
    if SKILL_REFS_DIR.parent.exists():
        SKILL_REFS_DIR.mkdir(parents=True, exist_ok=True)
        for md in sorted(AI_DOCS_DIR.glob("*.md")):
            (SKILL_REFS_DIR / md.name).write_text(md.read_text(encoding="utf-8"), encoding="utf-8")

    print(f"ai-docs: wrote {AI_DOCS_DIR.relative_to(REPO_ROOT)} and synced skill references")


if __name__ == "__main__":
    main()
